"""Tests for the AGP tag pre-run checks of pretext-to-asm and pretext-to-asm-recurate."""

from pathlib import Path
from unittest.mock import patch

import pytest
import rich_click as click

from grit.steps.post_curation.pretext_to_asm import _OUTPUT_SPECS, _run_pretext_to_asm_core
from grit.steps.post_curation.pretext_to_asm_recurate import _check_unloc_tags
from grit.utils.helpers import iter_agp_rows, parse_agp_tags

# Standard 9-column AGP row; PretextView appends its tags from column 10 on.
# Column 1 is PretextView's own object name, column 6 the component carried
# over from the assembly — that's where a previous round's unloc name lives.
_ROW = "{name}\t1\t1000\t1\tW\t{component}\t1\t1000\t+"


def _agp(path: Path, lines: list[str]) -> Path:
    header = [
        "##agp-version\t2.1",
        "# DESCRIPTION: Generated by PretextViewAI Version 1.0.6",
    ]
    path.write_text("\n".join(header + lines) + "\n")
    return path


def _core(ctx, tmp_path, agp_lines):
    """Run _run_pretext_to_asm_core against an on-disk AGP with a mocked pretext-to-asm."""
    ctx.workdir = tmp_path
    ctx.tracker = None
    (tmp_path / "original.fa").write_text(">seq\nACGT\n")
    _agp(tmp_path / f"{ctx.tol_id}.curated.agp", agp_lines)
    with patch("grit.steps.post_curation.pretext_to_asm._run") as mock_run:
        _run_pretext_to_asm_core(
            ctx,
            "pretext_to_asm",
            tmp_path / "original.fa",
            "missing original.fa",
            tmp_path,
            f"{ctx.tol_id}.fa",
            _OUTPUT_SPECS,
        )
    return mock_run


def test_parse_agp_tags_reads_extra_columns(tmp_path):
    agp = _agp(
        tmp_path / "x.agp",
        [
            _ROW.format(name="SUPER_1", component="SCAFFOLD_1") + "\tCut\tHAP1",
            _ROW.format(name="SUPER_2", component="SCAFFOLD_2"),
        ],
    )
    assert parse_agp_tags(agp) == {"SUPER_1": {"cut", "hap1"}, "SUPER_2": set()}


def test_parse_agp_tags_on_missing_file_is_empty(tmp_path):
    assert parse_agp_tags(tmp_path / "nope.agp") == {}


def test_primary_tag_present_passes(mock_ctx_primary, tmp_path):
    mock_ctx_primary.combine_for_curation = True
    mock_run = _core(
        mock_ctx_primary,
        tmp_path,
        [_ROW.format(name="SUPER_1", component="SCAFFOLD_1") + "\tPrimary"],
    )
    mock_run.assert_called_once()


def test_primary_tag_missing_fails_before_running(mock_ctx_primary, tmp_path):
    mock_ctx_primary.combine_for_curation = True
    with pytest.raises(click.ClickException) as exc:
        _core(
            mock_ctx_primary,
            tmp_path,
            [_ROW.format(name="SUPER_1", component="SCAFFOLD_1") + "\tHAP1"],
        )
    assert "primary" in str(exc.value).lower()
    assert "PretextView" in str(exc.value)


def test_primary_tag_not_required_without_combine_for_curation(mock_ctx_primary, tmp_path):
    """A single-hap assembly curated in its own window needs no primary tag."""
    assert mock_ctx_primary.combine_for_curation is False
    mock_run = _core(
        mock_ctx_primary, tmp_path, [_ROW.format(name="SUPER_1", component="SCAFFOLD_1")]
    )
    mock_run.assert_called_once()


def test_primary_tag_not_required_for_dual_hap_ticket(mock_ctx, tmp_path):
    """hap1/hap2 tickets are tagged per haplotype, not 'primary'."""
    assert mock_ctx.combine_for_curation is True
    mock_run = _core(
        mock_ctx, tmp_path, [_ROW.format(name="SUPER_1", component="SCAFFOLD_1") + "\tHAP1"]
    )
    mock_run.assert_called_once()


def test_unloc_check_passes_when_tag_reapplied(tmp_path):
    agp = _agp(
        tmp_path / "recurate.agp",
        [
            _ROW.format(name="Scaffold_1", component="SUPER_1_HAP1"),
            _ROW.format(name="Scaffold_1", component="SUPER_1_unloc_1_HAP1") + "\tPainted\tUnloc",
        ],
    )
    _check_unloc_tags(agp)


def test_unloc_check_fails_listing_untagged_components(tmp_path):
    agp = _agp(
        tmp_path / "recurate.agp",
        [
            _ROW.format(name="Scaffold_1", component="SUPER_1_HAP1"),
            _ROW.format(name="Scaffold_1", component="SUPER_1_unloc_1_HAP1"),
            _ROW.format(name="Scaffold_2", component="SUPER_2_unloc_3_HAP1") + "\tPainted",
            _ROW.format(name="Scaffold_3", component="SUPER_3_unloc_1_HAP1") + "\tUnloc",
        ],
    )
    with pytest.raises(click.ClickException) as exc:
        _check_unloc_tags(agp)
    message = str(exc.value)
    assert "SUPER_1_unloc_1_HAP1" in message
    assert "SUPER_2_unloc_3_HAP1" in message
    assert "SUPER_3_unloc_1_HAP1" not in message


def test_unloc_check_ignores_freshly_made_unlocs(tmp_path):
    """An unloc created in this round is tagged but its component keeps the raw scaffold name."""
    agp = _agp(
        tmp_path / "recurate.agp",
        [_ROW.format(name="Scaffold_1", component="HAP1_SCAFFOLD_681") + "\tPainted\tUnloc"],
    )
    _check_unloc_tags(agp)


@patch("grit.steps.post_curation.pretext_to_asm._run")
@patch("grit.steps.post_curation.pretext_to_asm_recurate.find_canonical_fa")
def test_recurate_step_applies_the_unloc_check(mock_find_fa, mock_run, mock_ctx, tmp_path):
    from grit.steps.post_curation.pretext_to_asm_recurate import run_pretext_to_asm_recurate

    mock_ctx.workdir = tmp_path
    mock_ctx.tracker = None
    original_fa = tmp_path / "canonical.fa"
    original_fa.write_text(">seq\nACGT\n")
    mock_find_fa.return_value = original_fa
