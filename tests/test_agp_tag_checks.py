_REAL_UNLOC_AGP = Path(__file__).parent / "fixtures" / "pretextviewai_unloc_tag.agp"


def test_iter_agp_rows_on_real_recurate_agp():
    """Real recurate AGP: the carried-over unloc name is the component (col 6), not the object."""
    rows = iter_agp_rows(_REAL_UNLOC_AGP)
    unlocs = {component: tags for _name, component, tags in rows if "unloc" in component.lower()}
    assert set(unlocs) == {"SUPER_X_unloc_1_HAP1", "SUPER_X_unloc_2_HAP1"}
    assert all("unloc" in tags for tags in unlocs.values())
    # every row of that scaffold shares the same PretextView object name
    assert {name for name, _component, _tags in rows} == {"Scaffold_4", "Scaffold_5"}


def test_unloc_check_accepts_real_tagged_recurate_agp():
    _check_unloc_tags(_REAL_UNLOC_AGP)


def test_unloc_check_fails_on_real_agp_with_the_tag_dropped(tmp_path):
    stripped = tmp_path / "untagged.agp"
    stripped.write_text(
        "\n".join(
            "\t".join(f for f in line.split("\t") if f.strip().lower() != "unloc")
            for line in _REAL_UNLOC_AGP.read_text().splitlines()
        )
    )
    with pytest.raises(click.ClickException) as exc:
        _check_unloc_tags(stripped)
    assert "SUPER_X_unloc_1_HAP1" in str(exc.value)
    assert "SUPER_X_unloc_2_HAP1" in str(exc.value)


_REAL_UNLOC_OBJECT_AGP = Path(__file__).parent / "fixtures" / "pretextviewai_unloc_object_name.agp"


